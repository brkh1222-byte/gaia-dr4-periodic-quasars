"""Write paper/results_macros.tex from an analysis output directory.

Usage: .venv/bin/python paper/fill_results.py results/dr4        (real data, after release)
       .venv/bin/python paper/fill_results.py results/dress_rehearsal_null --mock
With --mock every macro is wrapped so the PDF shows the numbers as MOCK values.
"""
import json
import sys
from pathlib import Path

import pandas as pd

tag = Path(sys.argv[1])
mock = "--mock" in sys.argv
pop = json.load(open(tag / "population.json"))
sc = pd.read_csv(tag / "scores.csv")
scored = sc[sc.status == "scored"]
h1, h2, h3 = pop["H1"], pop["H2"], pop["H3"]
vals = {
    "Nscored": len(scored),
    "Ntest": h1["n_testable"],
    "HoneK": h1["k"],
    "HoneExpected": f"{h1['expected']:.1f}",
    "HoneRate": f"{h1['rate']:.3f}",
    "HoneP": f"{h1['p_binom']:.2g}",
    "HoneVerdict": "an excess" if h1["reject_H0"] else "no excess",
    "NlnBthree": h2["n_lnB_gt3"],
    "Nsurv": len(h2["survivors"]),
    "Nspecific": len(h2.get("ephemeris_specific", [])),
    "Fmedian": f"{h3['f_median']:.2f}",
    "Fupper": f"{h3['f_upper95']:.2f}",
    "MedianLnB": f"{scored[scored.testable].lnB.median():.1f}",
    "MedianVisits": f"{scored.n_visits.median():.0f}",
}
lines = ["% generated by paper/fill_results.py from " + str(tag) + (" (MOCK DATA)" if mock else "")]
for k, v in vals.items():
    body = f"\\textit{{[mock: {v}]}}" if mock else str(v)
    lines.append(f"\\newcommand{{\\R{k}}}{{{body}}}")
Path(__file__).with_name("results_macros.tex").write_text("\n".join(lines) + "\n")
import shutil
if (tag / "fig1.pdf").exists():
    shutil.copy(tag / "fig1.pdf", Path(__file__).with_name("fig1.pdf"))
print("\n".join(lines))
